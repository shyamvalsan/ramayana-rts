#!/usr/bin/env node
// Generates illustrative images via OpenAI's gpt-image-2 API and saves them
// to public/sprites/. Quality=low for cost; style prompt prefix is shared so
// the set looks like one art direction. Retries once on transient errors.
//
// Usage: OPENAI_API_KEY=sk-... node scripts/gen-images.mjs [manifest_key]
// If a manifest key is provided, only that one image is generated.

import fs from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SPRITES_DIR = path.join(ROOT, 'public', 'sprites');
const ENV_PATH = path.join(ROOT, '.env');
const STORY_PATH = path.join(ROOT, 'scripts', 'story.json');

// If scripts/story.json exists (generated by scripts/gen-story.mjs), load its
// cutscene panels and merge them into the manifest, overriding any hard-coded
// cutscene-* entries below.
async function loadStoryPanels() {
  try {
    const raw = await fs.readFile(STORY_PATH, 'utf-8');
    const data = JSON.parse(raw);
    if (!Array.isArray(data.panels)) return [];
    return data.panels.map(p => ({
      key: p.id,            // e.g. "cutscene-01"
      kind: 'scene',
      size: '1536x1024',
      prompt: p.scene_prompt,
    }));
  } catch {
    return [];
  }
}

// Read OPENAI_API_KEY from .env if not already set.
async function loadEnv() {
  if (process.env.OPENAI_API_KEY) return;
  try {
    const data = await fs.readFile(ENV_PATH, 'utf-8');
    for (const line of data.split('\n')) {
      const m = line.match(/^([A-Z_]+)=(.*)$/);
      if (m) process.env[m[1]] = m[2].trim();
    }
  } catch {}
}

