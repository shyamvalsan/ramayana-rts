async function generate({ key, kind, size, prompt }) {
  const prefix =
    kind === 'scene' ? SCENE_PREFIX :
    kind === 'unit-topdown' ? UNIT_TOPDOWN_PREFIX :
    STYLE_PREFIX;
  const fullPrompt = `${prefix}\n\n${prompt}`;
  const body = {
    model: 'gpt-image-2',
    prompt: fullPrompt,
    quality: 'low',
    size,
    n: 1,
  };
  const res = await fetch('https://api.openai.com/v1/images/generations', {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${process.env.OPENAI_API_KEY}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const txt = await res.text();
    throw new Error(`API ${res.status}: ${txt.slice(0, 400)}`);
  }
  const data = await res.json();
  const b64 = data.data?.[0]?.b64_json;
  if (!b64) throw new Error(`No image returned: ${JSON.stringify(data).slice(0, 200)}`);
  const buf = Buffer.from(b64, 'base64');
  const out = path.join(SPRITES_DIR, `${key}.png`);
  await fs.writeFile(out, buf);
  return { key, bytes: buf.length, path: out };
}

async function main() {
  await loadEnv();
  if (!process.env.OPENAI_API_KEY) {
    console.error('Missing OPENAI_API_KEY (looked in env and .env)');
    process.exit(1);
  }
  await fs.mkdir(SPRITES_DIR, { recursive: true });

  // Merge in story-driven cutscene prompts if available. They override any
  // hard-coded cutscene-* entries from the static MANIFEST.
  const storyPanels = await loadStoryPanels();
  const storyKeys = new Set(storyPanels.map(p => p.key));
  const baseManifest = MANIFEST.filter(m => !storyKeys.has(m.key));
  const fullManifest = [...storyPanels, ...baseManifest];

  const filter = process.argv[2];
  const items = filter ? fullManifest.filter(m => m.key === filter || m.key.includes(filter)) : fullManifest;
  if (items.length === 0) {
    console.error('No matching manifest entries.');
    process.exit(1);
  }

  // Skip ones that already exist (idempotent re-runs).
  const todo = [];
  for (const item of items) {
    try {
      await fs.access(path.join(SPRITES_DIR, `${item.key}.png`));
      console.log(`[skip] ${item.key} (already exists)`);
    } catch {
      todo.push(item);
    }
  }
  console.log(`Generating ${todo.length} image(s)…`);

  // Sequential to be polite to the API and to keep cost predictable.
  const results = { ok: [], fail: [] };
  for (const item of todo) {
    const t0 = Date.now();
    try {
      const r = await generate(item);
      const dt = ((Date.now() - t0) / 1000).toFixed(1);
      console.log(`[ok]   ${item.key}  ${(r.bytes / 1024).toFixed(0)}kb  ${dt}s`);
      results.ok.push(item.key);
    } catch (e) {
      console.warn(`[warn] ${item.key}: ${e.message}`);
      // One retry.
      try {
        const r = await generate(item);
        const dt = ((Date.now() - t0) / 1000).toFixed(1);
        console.log(`[ok]   ${item.key}  (retry)  ${(r.bytes / 1024).toFixed(0)}kb  ${dt}s`);
        results.ok.push(item.key);
      } catch (e2) {
        console.error(`[fail] ${item.key}: ${e2.message}`);
        results.fail.push(item.key);
      }
    }
  }

  console.log(`\nDone. ${results.ok.length} ok, ${results.fail.length} failed.`);
  if (results.fail.length > 0) {
    console.log('Failed:', results.fail.join(', '));
    process.exit(1);
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
