export function preloadSprites(onReady?: () => void) {
  let pending = SPRITE_KEYS.length + SCENE_KEYS.length + TERRAIN_KEYS.length;
  const tick = () => {
    pending--;
    if (pending <= 0 && onReady) onReady();
  };
  for (const key of SPRITE_KEYS) {
    const img = new Image();
    img.crossOrigin = 'anonymous';
    img.onload = () => {
      // Build a chroma-keyed version (cream bg → transparent).
      try {
        KEYED.set(key, chromaKeyCream(img));
      } catch (e) {
        // Canvas tainting can fail on some setups; fall back to the raw image.
        KEYED.set(key, null);
      }
      tick();
    };
    img.onerror = () => { CACHE.set(key, null); tick(); };
    img.src = asset(`sprites/${key}.png`);
    CACHE.set(key, img);
  }
  for (const key of SCENE_KEYS) {
    const img = new Image();
    img.onload = () => tick();
    img.onerror = () => { CACHE.set(key, null); tick(); };
    img.src = asset(`sprites/${key}.png`);
    CACHE.set(key, img);
  }
  // Terrain tile textures — pre-scale to ~256px so they tile densely without
  // looking like one giant 1024px stamp repeated.
  for (const key of TERRAIN_KEYS) {
    const img = new Image();
    img.onload = () => {
      try {
        const target = 256;
        const c = document.createElement('canvas');
        c.width = target;
        c.height = target;
        const cx = c.getContext('2d')!;
        cx.imageSmoothingQuality = 'high';
        cx.drawImage(img, 0, 0, target, target);
        TERRAIN.set(key, c);
      } catch (e) {
        TERRAIN.set(key, null);
      }
      tick();
    };
    img.onerror = () => { TERRAIN.set(key, null); tick(); };
    img.src = asset(`sprites/${key}.png`);
    CACHE.set(key, img);
  }
}

export function getTerrainTile(key: string): HTMLCanvasElement | null {
  return TERRAIN.get(key) ?? null;
}

export function getSprite(key: string): HTMLCanvasElement | HTMLImageElement | null {
  // Prefer the chroma-keyed canvas if available.
  const keyed = KEYED.get(key);
  if (keyed) return keyed;
  const img = CACHE.get(key);
  if (img && img.complete && img.naturalWidth > 0) return img;
  return null;
}

export function getScene(key: string): HTMLImageElement | null {
  const img = CACHE.get(key);
  if (img && img instanceof HTMLImageElement && img.complete && img.naturalWidth > 0) return img;
  return null;
}

