// Campaign bosses/buildings borrow an existing type's sprite set via
// def.spriteBase (e.g. khara draws with subahu's art). Every typeId→key
// mapper resolves through these first.
function unitSpriteType(typeId: string): string {
  return UNIT_DEFS[typeId]?.spriteBase ?? typeId;
}
function buildingSpriteType(typeId: string): string {
  return BUILDING_DEFS[typeId]?.spriteBase ?? typeId;
}

