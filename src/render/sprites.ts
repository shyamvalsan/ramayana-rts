// Sprite loader. Pre-loads PNGs from /sprites/ and exposes a synchronous
// getter the renderer can call from a hot path. Each sprite is loaded once,
// background-keyed (cream → transparent) for "sprite" type assets, and cached.
//
// Asset naming convention (matches scripts/gen-images.mjs):
//   building-{typeId}.png   — building portraits
//   unit-{typeId}.png       — unit portraits
//   resource-{typeId}.png   — resource icons
//   {scene-key}.png         — full-bleed scene backgrounds

