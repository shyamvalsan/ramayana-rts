const warnedActionMisses = new Set<string>();

// Action pose sprite, used while the unit is performing a specific action.
// Returns the sprite key + horizontal-flip flag based on the unit's facing.
export function unitActionSprite(typeId: string, action: 'chop' | 'gather' | 'build' | 'attack' | 'shoot' | 'claw' | 'hunt', facing: number | undefined):
    { key: string; flip: boolean } | null {
  typeId = unitSpriteType(typeId);
  // Map typeId+action to a sprite key. Returns null if no specific sprite exists.
  let key: string | null = null;
  switch (typeId) {
    case 'villager':
      if (action === 'chop') key = 'topdown-villager-chop';
      else if (action === 'gather') key = 'topdown-villager-gather';
      else if (action === 'build') key = 'topdown-villager-build';
      else if (action === 'hunt') key = 'topdown-villager-chop';
      else if (action === 'attack') key = 'topdown-villager-chop';
      break;
    case 'villager_enemy':
      if (action === 'attack') key = 'topdown-grunt_enemy-attack';
      break;
    case 'spearman':
    case 'spearman_enemy':
      if (action === 'attack') key = 'topdown-spearman-attack';
      break;
    case 'archer':
    case 'archer_enemy':
      if (action === 'attack' || action === 'shoot') key = 'topdown-archer-shoot';
      break;
    case 'cavalry':
    case 'cavalry_enemy':
      if (action === 'attack') key = 'topdown-cavalry-attack';
      break;
    case 'rama':
      if (action === 'attack' || action === 'shoot') key = 'topdown-rama-shoot';
      break;
    case 'lakshmana':
      if (action === 'attack' || action === 'shoot') key = 'topdown-lakshmana-shoot';
      break;
    case 'tataka':
      if (action === 'attack' || action === 'claw') key = 'topdown-tataka-claw';
      break;
    case 'subahu':
      if (action === 'attack') key = 'topdown-subahu-attack';
      break;
    case 'maricha':
      if (action === 'attack' || action === 'shoot') key = 'topdown-maricha-shoot';
      break;
    case 'grunt_enemy':
      if (action === 'attack') key = 'topdown-grunt_enemy-attack';
      break;
  }
  if (!key) {
    if (import.meta.env?.DEV && (action === 'attack' || action === 'shoot' || action === 'claw')) {
      const w = warnedActionMisses;
      const tag = `${typeId}+${action}`;
      if (!w.has(tag)) { w.add(tag); console.warn(`[sprites] no action sprite for ${tag} — falling back to directional`); }
    }
    return null;
  }
  // Action sprites are drawn facing east (right). If the unit's facing has a
  // westward component, flip horizontally.
  if (facing === undefined || !Number.isFinite(facing)) return { key, flip: false };
  let a = facing;
  while (a < 0) a += Math.PI * 2;
  while (a >= Math.PI * 2) a -= Math.PI * 2;
  // Flip when facing left (W side: π/2 < a < 3π/2).
  const flip = a > Math.PI / 2 && a < (3 * Math.PI) / 2;
  return { key, flip };
}

