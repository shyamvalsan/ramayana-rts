// Convert the cream-background sprite to one with the background made
// transparent. Samples the perimeter to pick a robust background color,
// chroma-keys with tolerance bands, then trims the transparent margins so
// the resulting canvas is tightly cropped around the subject (eliminates
// the "halo of padding" that compounded with downscaling caused fringes).
function chromaKeyCream(img: HTMLImageElement): HTMLCanvasElement {
  const W = img.naturalWidth;
  const H = img.naturalHeight;
  const src = document.createElement('canvas');
  src.width = W;
  src.height = H;
  const cx = src.getContext('2d')!;
  cx.drawImage(img, 0, 0);
  const data = cx.getImageData(0, 0, W, H);
  const p = data.data;

  // Sample background along the perimeter (64 points for robustness).
  let r = 0, g = 0, b = 0, n = 0;
  const sample = (x: number, y: number) => {
    const i = (y * W + x) * 4;
    r += p[i]; g += p[i + 1]; b += p[i + 2]; n++;
  };
  for (let i = 0; i < 16; i++) {
    const t = i / 15;
    sample(Math.floor(t * (W - 1)), 0);
    sample(Math.floor(t * (W - 1)), H - 1);
    sample(0, Math.floor(t * (H - 1)));
    sample(W - 1, Math.floor(t * (H - 1)));
  }
  const bgR = r / n, bgG = g / n, bgB = b / n;

  const tol = 48;
  const tolSoft = 82;
  for (let i = 0; i < p.length; i += 4) {
    const dr = p[i] - bgR, dg = p[i + 1] - bgG, db = p[i + 2] - bgB;
    const d = Math.sqrt(dr * dr + dg * dg + db * db);
    if (d < tol) {
      p[i + 3] = 0;
    } else if (d < tolSoft) {
      const a = (d - tol) / (tolSoft - tol);
      p[i + 3] = Math.floor(p[i + 3] * a);
      // Despill: pull the residual cream tint out of the soft edge.
      const k = 1 - a;
      p[i] = Math.max(0, p[i] - bgR * k * 0.5);
      p[i + 1] = Math.max(0, p[i + 1] - bgG * k * 0.5);
      p[i + 2] = Math.max(0, p[i + 2] - bgB * k * 0.5);
    }
  }
  cx.putImageData(data, 0, 0);

  // Auto-crop: find the tight bounding box of non-transparent pixels.
  let minX = W, minY = H, maxX = -1, maxY = -1;
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      const a = p[(y * W + x) * 4 + 3];
      if (a > 8) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
  }
  if (maxX < minX) {
    // No subject found (chroma-key removed everything). Fall back to full image.
    minX = 0; minY = 0; maxX = W - 1; maxY = H - 1;
  }
  const cw = maxX - minX + 1;
  const ch = maxY - minY + 1;

  // Pre-scale down to a friendlier render resolution (max edge 256).
  const maxEdge = 256;
  let dstW = cw, dstH = ch;
  if (Math.max(cw, ch) > maxEdge) {
    if (cw >= ch) { dstW = maxEdge; dstH = Math.round(ch * maxEdge / cw); }
    else { dstH = maxEdge; dstW = Math.round(cw * maxEdge / ch); }
  }
  const dst = document.createElement('canvas');
  dst.width = dstW;
  dst.height = dstH;
  const dcx = dst.getContext('2d')!;
  dcx.imageSmoothingEnabled = true;
  dcx.imageSmoothingQuality = 'high';
  dcx.drawImage(src, minX, minY, cw, ch, 0, 0, dstW, dstH);
  return dst;
}
